"""Build the standalone Welcome Edge Function from reviewed local sources."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
portal=(root/'backend/portal-public.ts').read_text()
shared=portal[portal.index('const module_1='):portal.index('const module_6=')]
auth=(root/'deployment/manual-accounts/auth-handler.js').read_text()
password=auth[auth.index('export async function passwordKey'):auth.index('export function createManualAuthHandler')].replace('export ', '')
handler=(root/'backend/alliance-welcome-handler.mjs').read_text().split('\n',1)[1].replace('export function createWelcomeHandler','function createWelcomeHandler')
entry="""const env=Deno.env;
const welcomeRpc=module_2.createRpc(env.get('SUPABASE_URL'),module_1.serverKey(env));
Deno.serve(createWelcomeHandler({rpc:(action,args)=>welcomeRpc('transfer_welcome',{action,args}),verifyIdentity:module_3.firebaseVerifier({projectId:env.get('FIREBASE_PROJECT_ID'),apiKey:env.get('FIREBASE_API_KEY')})}));
"""
(root/'backend/alliance-welcome.bundle.ts').write_text('// Generated by tools/build-welcome.py; edit source modules instead.\n'+shared+password+handler+'\n'+entry)
